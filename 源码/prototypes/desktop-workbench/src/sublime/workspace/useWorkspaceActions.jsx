import React from 'react';
import { useWorkspaceRoute } from './useWorkspaceRoute.jsx';
import { useWorkspaceSession } from './useWorkspaceSession.jsx';
import { useBackupRestore } from './BackupRestoreReview.jsx';
import { useDraftRecovery } from './useDraftRecovery.jsx';
import { useCardActions } from './useCardActions.jsx';
import { useArticleActions } from './useArticleActions.jsx';
import { useReaderActions } from './useReaderActions.jsx';
import { useShareExport } from './useShareExport.jsx';
import { useAiDrafts } from './useAiDrafts.jsx';
import { usePodcastJobs } from './usePodcastJobs.jsx';
import { useRelatedCards } from './useRelatedCards.jsx';
export function useWorkspaceActions({
  activeSearchScope,
  searches,
  setPopover,
  setModal,
  setEditorDraft,
  navigation,
  loadedIdentity,
  identityId,
  setSelected,
  setSelectionMode,
  meaningActive,
  setFilters,
  meaningCache,
  libraryCards,
  current,
  notify,
  session,
  setNoteDraft,
  stateRef,
  cards,
  popover,
  draftKey,
  ready,
  epoch,
  setSaving,
  draftRef,
  setState,
  setError,
  documentJobs,
  documentWaiters,
  modalRef,
  readerFlush,
  aiVolatile,
  podcastVolatile,
  backupRead,
  modal,
  viewRef,
  viewVersion,
  setRecoveryEditorVersion,
  editing,
  nativeIds,
  saveOptionDrafts,
  clipperView,
  saved,
  originalPosition,
  api,
  sourceOpen,
  setArticleNavigation,
  setReaderNavigation,
  setCheckingSource,
  currentCollection,
  collectionDraftKey,
  state,
  setAiRevision,
  podcastJobs,
  podcastRequests,
  personalSearch,
  filters,
  identityFor,
  selectionMode,
  selected,
  membership,
  relatedCache,
  relatedViews,
  demo,
}) {
  const { navigate, changeRecallArchive, finishSelection, changeSearchMode, changeLibraryQuery, openNoteReference, openNote, showAi, openEditor, editDraft } =
    useWorkspaceRoute({
      activeSearchScope,
      searches,
      setPopover,
      setModal,
      setEditorDraft,
      navigation,
      loadedIdentity,
      identityId,
      commit: (...args) => commit(...args),
      setSelected,
      setSelectionMode,
      meaningActive,
      setFilters,
      meaningCache,
      libraryCards,
      current,
      notify,
      session,
      setNoteDraft,
      stateRef,
      cards,
      popover,
      perform: (...args) => perform(...args),
      draftKey,
    });
  const { commit, perform, saveDraft, settleDocumentJobs } = useWorkspaceSession({
    ready,
    epoch,
    setSaving,
    session,
    draftRef,
    stateRef,
    setState,
    setError,
    notify,
    documentJobs,
    documentWaiters,
  });
  const backupRestore = useBackupRestore({
    modal,
    cards,
    identityId,
    documentJobs,
    documentWaiters,
    viewRef,
    epoch,
    session,
    modalRef,
    navigate,
    notify,
    setError,
  });
  const { backup, previewBackupText, openPastedBackup, updatePastedBackup, previewPastedBackup, readBackupFile, recoverDraft } = useDraftRecovery({
    epoch,
    modalRef,
    readerFlush,
    settleDocumentJobs: (...args) => settleDocumentJobs(...args),
    identityId,
    session,
    aiVolatile,
    podcastVolatile,
    setError,
    setPopover,
    setModal,
    notify,
    backupRead,
    modal,
    viewRef,
    viewVersion,
    loadedIdentity,
    cards,
    navigate: (...args) => navigate(...args),
    setEditorDraft,
    openEditor: (...args) => openEditor(...args),
    openNote: (...args) => openNote(...args),
    setNoteDraft,
    setRecoveryEditorVersion,
    commit: (...args) => commit(...args),
    setSaving,
  });
  const {
    saveCard,
    saveBookCover,
    setBookClassification,
    toggleSave,
    saveCardOptions,
    removeSavedCard,
    arrangeButton,
    relatedActions,
    copyText,
    renderOriginalPosition,
    cardActions,
  } = useCardActions({
    editing,
    draftKey,
    stateRef,
    commit: (...args) => commit(...args),
    setEditorDraft,
    navigate: (...args) => navigate(...args),
    notify,
    modal,
    setModal,
    setPopover,
    nativeIds,
    saveOptionDrafts,
    epoch,
    loadedIdentity,
    identityId,
    clipperView,
    perform: (...args) => perform(...args),
    saved,
    popover,
    share: (...args) => share(...args),
    originalPosition,
    startLinkedNote: (...args) => startLinkedNote(...args),
  });
  const { saveDocumentExcerpt, saveDocumentExcerptTask, saveArticleDraft, saveArticleHighlight, collectArticleFigure } = useArticleActions({
    documentJobs,
    identityId,
    documentWaiters,
    epoch,
    viewRef,
    viewVersion,
    commit: (...args) => commit(...args),
    navigate: (...args) => navigate(...args),
    notify,
    setError,
    loadedIdentity,
    session,
    api,
  });
  const { updateReader, saveReaderExcerpt, openCardSource } = useReaderActions({
    current,
    epoch,
    commit: (...args) => commit(...args),
    notify,
    viewRef,
    sourceOpen,
    viewVersion,
    stateRef,
    cards,
    setError,
    libraryCards,
    setArticleNavigation,
    navigate: (...args) => navigate(...args),
    setReaderNavigation,
    setCheckingSource,
  });
  const { share, exportShare, importRecords, setCollectionPinned, saveCollection, createBoard, exportText, openExport, toggleSelect } = useShareExport({
    setPopover,
    setModal,
    epoch,
    modal,
    setSaving,
    notify,
    setError,
    session,
    viewRef,
    modalRef,
    commit: (...args) => commit(...args),
    cards,
    navigate: (...args) => navigate(...args),
    perform: (...args) => perform(...args),
    currentCollection,
    collectionDraftKey,
    state,
    setSelected,
  });
  const { saveEnrichment, persistAiResult, aiResultDrafts, restoreAiSource, saveInsight } = useAiDrafts({
    epoch,
    commit: (...args) => commit(...args),
    notify,
    identityId,
    aiVolatile,
    setAiRevision,
    session,
    loadedIdentity,
    setError,
    stateRef,
    draftRef,
    setState,
    state,
    cards,
    api,
  });
  const {
    savePodcast,
    podcastResultDrafts,
    podcastResultIsDurable,
    clearPersistedPodcastResult,
    persistPodcastTranscript,
    transcribePodcast,
    transcribePodcastTask,
    recoverPodcastTranscript,
  } = usePodcastJobs({
    epoch,
    commit: (...args) => commit(...args),
    navigate: (...args) => navigate(...args),
    notify,
    state,
    podcastVolatile,
    identityId,
    setAiRevision,
    session,
    loadedIdentity,
    stateRef,
    draftRef,
    setState,
    podcastJobs,
    podcastRequests,
    api,
    setError,
  });
  const { tile, relatedContent, startLinkedNote } = useRelatedCards({
    popover,
    relatedActions: (...args) => relatedActions(...args),
    personalSearch,
    meaningActive,
    filters,
    navigate: (...args) => navigate(...args),
    identityFor,
    libraryCards,
    state,
    selectionMode,
    selected,
    toggleSelect: (...args) => toggleSelect(...args),
    membership,
    openCardSource: (...args) => openCardSource(...args),
    setArticleNavigation,
    identityId,
    api,
    relatedCache,
    relatedViews,
    epoch,
    session,
    demo,
    clipperView,
    commit: (...args) => commit(...args),
    loadedIdentity,
    setPopover,
    setModal,
    setError,
  });
  return {
    navigate,
    changeRecallArchive,
    finishSelection,
    changeSearchMode,
    changeLibraryQuery,
    openNoteReference,
    openNote,
    showAi,
    openEditor,
    editDraft,
    commit,
    perform,
    saveDraft,
    settleDocumentJobs,
    ...backupRestore,
    backup,
    previewBackupText,
    openPastedBackup,
    updatePastedBackup,
    previewPastedBackup,
    readBackupFile,
    recoverDraft,
    saveCard,
    saveBookCover,
    setBookClassification,
    toggleSave,
    saveCardOptions,
    removeSavedCard,
    arrangeButton,
    relatedActions,
    copyText,
    renderOriginalPosition,
    cardActions,
    saveDocumentExcerpt,
    saveDocumentExcerptTask,
    saveArticleDraft,
    saveArticleHighlight,
    collectArticleFigure,
    updateReader,
    saveReaderExcerpt,
    openCardSource,
    share,
    exportShare,
    importRecords,
    setCollectionPinned,
    saveCollection,
    createBoard,
    exportText,
    openExport,
    toggleSelect,
    saveEnrichment,
    persistAiResult,
    aiResultDrafts,
    restoreAiSource,
    saveInsight,
    savePodcast,
    podcastResultDrafts,
    podcastResultIsDurable,
    clearPersistedPodcastResult,
    persistPodcastTranscript,
    transcribePodcast,
    transcribePodcastTask,
    recoverPodcastTranscript,
    tile,
    relatedContent,
    startLinkedNote,
  };
}
